// Queue logic.
//
// Rules:
//  - queue[0] is the song playing right now; queue[1..] is "Up Next".
//  - The whole queue never holds more than QUEUE_MAX (30) songs, no duplicates.
//  - When a song finishes (or is skipped) it is removed from the queue.
//  - Auto Queue tops the queue up with similar songs, up to the limit.

const QUEUE_MAX = 30;
const AUTO_FILL_WHEN_AT_OR_BELOW = 5;   // top up when this few songs remain
const PLAYED_MAX = 25;                  // how many finished songs "Previous" can bring back

let queue = [];
let playedStack = [];                   // finished songs, newest last
const recentIds = new Set();            // played this session, so Auto Queue avoids repeats
let playToken = 0;                      // guards against out-of-date stream responses

const relatedInFlight = new Map();      // seed id -> promise, so one seed is never fetched twice at once
const relatedFetched = new Set();       // seeds we already pulled related songs for
let queueEpoch = 0;                     // bumps when the queue is rebuilt; stale Auto Queue results are dropped

// Queue entries are copies of tracks. entry.manual === true means the user added or arranged it
// (those stay when a new song is played); everything else was generated by Auto Queue.
function entry(track, manual) { return { ...track, manual: !!manual }; }

function currentTrack() { return queue[0] || null; }
function inQueue(id) { return queue.some(t => t.id === id); }

// Where the next manually added song goes: right after the current song and any
// manual songs already waiting (so they play in the order they were added).
function nextManualSlot() {
  let i = 1;
  while (i < queue.length && queue[i].manual) i++;
  return i;
}

function pushPlayed(track) {
  if (!track) return;
  playedStack.push(track);
  if (playedStack.length > PLAYED_MAX) playedStack.shift();
  recentIds.add(track.id);
}

function queueChanged() {
  renderQueueUI();
  renderActiveScreen();
}

// ---- Adding ----

// Manual add = "play next": goes right after the current song (behind earlier manual adds).
function addToQueue(track) {
  if (!track || !track.id) return false;
  remember(track);

  const cur = currentTrack();
  if (!cur) {                           // nothing playing: just play it
    queue = [entry(track, false)];
    startCurrent();
    return true;
  }
  if (cur.id === track.id) { toast('That song is playing now'); return false; }

  const existing = queue.findIndex(t => t.id === track.id);
  if (existing > 0) {
    if (queue[existing].manual) { toast('Already in your queue'); return false; }
    queue.splice(existing, 1);          // an Auto Queue song: promote it to "next"
  } else if (queue.length >= QUEUE_MAX) {
    // Full: make room by dropping the last auto-generated song.
    let drop = -1;
    for (let i = queue.length - 1; i >= 1; i--) { if (!queue[i].manual) { drop = i; break; } }
    if (drop < 0) { toast(`Queue is full (${QUEUE_MAX} songs max)`); return false; }
    queue.splice(drop, 1);
  }

  queue.splice(nextManualSlot(), 0, entry(track, true));
  queueChanged();
  toast('Added to play next');
  return true;
}

// Play a song right now. Songs the user added or arranged stay in Up Next;
// the auto-generated ones are thrown away and refreshed from the new song.
function playNow(track) {
  if (!track || !track.id) return;
  remember(track);
  const cur = currentTrack();
  if (cur && cur.id === track.id) { startCurrent(); return; }

  const keep = queue.slice(1).filter(t => t.manual && t.id !== track.id);
  if (cur) pushPlayed(cur);             // the song we are leaving counts as done
  queue = [entry(track, false), ...keep].slice(0, QUEUE_MAX);

  queueEpoch++;                         // discard Auto Queue fetches started for the old queue
  relatedFetched.delete(track.id);
  if (autoQueueEnabled) loadRelatedTracks(track.id);
  startCurrent();
}

// Replace the queue with a list (playlist, liked songs). Capped at QUEUE_MAX.
function playList(tracks) {
  const seen = new Set();
  const list = [];
  (tracks || []).forEach(t => {
    if (t && t.id && !seen.has(t.id)) { seen.add(t.id); remember(t); list.push(entry(t, true)); }
  });
  if (!list.length) return;
  if (queue[0]) pushPlayed(queue[0]);
  queue = list.slice(0, QUEUE_MAX);
  queueEpoch++;
  if (list.length > QUEUE_MAX) toast(`Queue holds ${QUEUE_MAX} songs, loaded the first ${QUEUE_MAX}`);
  startCurrent();
}

// ---- Up Next management ----

function removeFromUpNext(index) {
  if (index < 1 || index >= queue.length) return;
  queue.splice(index, 1);
  queueChanged();
  maybeAutoQueue();
}

function playFromUpNext(index) {
  if (index < 1 || index >= queue.length) return;
  const [picked] = queue.splice(index, 1);
  pushPlayed(queue.shift());            // current song is done
  queue.unshift(picked);
  startCurrent();
}

function clearUpNext() {
  queue = queue.slice(0, 1);
  queueEpoch++;
  queueChanged();
}

// Drag-to-reorder: indices are positions in `queue` (so >= 1). A song the user
// moved counts as manual, so it stays when a new song is played.
function moveInUpNext(from, to) {
  if (from < 1 || to < 1 || from >= queue.length || to >= queue.length || from === to) return;
  const [moved] = queue.splice(from, 1);
  queue.splice(to, 0, entry(moved, true));
  queueChanged();
}

// ---- Moving between songs ----

async function playNextTrack() {
  const finished = currentTrack();
  if (!finished) return;

  if (shuffleOn && queue.length > 2) {
    const j = 1 + Math.floor(Math.random() * (queue.length - 1));
    const [t] = queue.splice(j, 1);
    queue.splice(1, 0, t);
  }

  if (queue.length > 1) {
    pushPlayed(queue.shift());          // finished song leaves the queue
    startCurrent();
    return;
  }

  // Last song: let Auto Queue find more before giving up.
  if (autoQueueEnabled) {
    setStatusTitle('Finding similar songs...');
    await loadRelatedTracks(finished.id);
    if (currentTrack() !== finished) return;   // user changed song meanwhile
    if (queue.length > 1) {
      pushPlayed(queue.shift());
      startCurrent();
      return;
    }
  }

  // Nothing left to play.
  pushPlayed(queue.shift());
  playToken++;
  stopPlayback();
  queueChanged();
}

function playPreviousTrack() {
  if (audio.currentTime > 3 || !playedStack.length) {
    if (currentTrack()) audio.currentTime = 0;
    return;
  }
  queue.unshift(playedStack.pop());
  if (queue.length > QUEUE_MAX) queue.length = QUEUE_MAX;
  startCurrent();
}

// ---- Auto Queue ----

// Fetch similar songs and append the ones that fit (no duplicates, never past QUEUE_MAX).
function loadRelatedTracks(videoId) {
  if (!videoId) return Promise.resolve(0);
  if (relatedInFlight.has(videoId)) return relatedInFlight.get(videoId);
  if (relatedFetched.has(videoId)) return Promise.resolve(0);

  const epoch = queueEpoch;
  const promise = (async () => {
    let added = 0;
    try {
      const tracks = await apiRelated(videoId);
      if (epoch !== queueEpoch) return 0;   // queue was rebuilt meanwhile; these songs are stale
      relatedFetched.add(videoId);      // only on success, so failures can retry

      const room = () => QUEUE_MAX - queue.length;
      const take = skipRecent => {
        for (const t of tracks) {
          if (room() <= 0) break;
          if (inQueue(t.id) || (skipRecent && recentIds.has(t.id))) continue;
          remember(t);
          queue.push(t);
          added++;
        }
      };
      take(true);                       // prefer songs not played yet
      if (!added) take(false);          // otherwise allow repeats rather than stopping
      if (added) queueChanged();
    } catch (err) {
      console.error('Auto queue error:', err);
    }
    return added;
  })().finally(() => { relatedInFlight.delete(videoId); });

  relatedInFlight.set(videoId, promise);
  return promise;
}

function maybeAutoQueue() {
  if (!autoQueueEnabled || !queue.length) return;
  if (relatedInFlight.size) return;     // a fetch is already on its way
  if (queue.length > AUTO_FILL_WHEN_AT_OR_BELOW || queue.length >= QUEUE_MAX) return;
  // Seed from the newest song that has not been used as a seed yet.
  const seed = [...queue].reverse().find(t => !relatedFetched.has(t.id));
  if (seed) loadRelatedTracks(seed.id);
}

// ---- Start playing queue[0] ----

async function startCurrent() {
  const track = currentTrack();
  if (!track) return;
  remember(track);
  recentIds.add(track.id);
  const myToken = ++playToken;

  setNowPlaying(track, 'Loading...');
  queueChanged();
  maybeAutoQueue();

  try {
    const data = await apiStream(track.id);
    if (myToken !== playToken) return;  // user already moved on

    if (!data || data.error || !data.stream_url) {
      setNowPlaying(track, 'Error playing track');
      toast("Couldn't play this song");
      skipAfterError(track);
      return;
    }
    audio.src = data.stream_url;
    setNowPlaying(track);
    await audio.play();
    updateMediaSession(track);
  } catch (err) {
    if (myToken !== playToken) return;
    console.error('Playback error:', err);
    setNowPlaying(track, 'Error playing track');
    skipAfterError(track);
  }
}

function skipAfterError(track) {
  setTimeout(() => {
    if (currentTrack() === track && queue.length > 1) playNextTrack();
  }, 1500);
}
